#!/bin/bash
# SQL for a database Lite shares with a running ProcessGPT (<tenant>.process-gpt.io/lite), to be
# reviewed and run by its operator in the Supabase SQL Editor — nothing here connects to a database.
# migrate.sh is for the Compose install's own database and is not used there: it builds process-gpt's
# schema and registers Lite's MCP servers in a tenant, which a shared database already has / must not get.
#
#   install/db/prod-sql.sh <out-dir>              everything (first deployment)
#   install/db/prod-sql.sh <out-dir> 019_x.sql    server/sql files from that one on (later deployments;
#                                                 `select name from lite_migrations` says what is applied)
#
# Writes <out-dir>/lite-prod-core.sql and, on a first deployment, <out-dir>/lite-prod-handover.sql.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../.." && pwd)
out=${1:?out-dir}
from=${2:-}
mkdir -p "$out"

# statements that only make sense for a single-tenant install (its 'localhost' tenant's MCP list)
strip_local() { perl -0pe "s/^update tenants set mcp = .*?where id = 'localhost';\n//gms"; }

{
  echo "-- Process GPT Lite on a shared ProcessGPT database: generated by install/db/prod-sql.sh from $(git -C "$root" rev-parse --short HEAD)"
  echo "-- Run once in the Supabase SQL Editor. Every file below is idempotent; the compatibility part"
  echo "-- (first deployment only) adds nothing a current ProcessGPT database already has."
  echo "begin;"
  echo "create table if not exists public.lite_migrations (name text primary key, applied_at timestamptz default now());"
  if [ -z "$from" ]; then
    for c in "$here"/compat/0[124]_*.sql; do echo; echo "-- ==== compat/$(basename "$c")"; cat "$c"; done
  fi
  for f in $(ls "$root"/server/sql/[0-9]*.sql | sort); do
    n=$(basename "$f")
    [[ -n "$from" && "$n" < "$from" ]] && continue
    echo; echo "-- ==== server/sql/$n"
    strip_local < "$f"
    echo; echo "insert into public.lite_migrations(name) values ('$n') on conflict do nothing;"
  done
  echo "commit;"
  echo "notify pgrst, 'reload schema';"
} > "$out/lite-prod-core.sql"

if [ -z "$from" ]; then
  {
    echo "-- Process GPT Lite: 인계 기록(handover_events)·역량 모델. Run ONLY if this returns a row with false:"
    echo "--   select to_regclass('public.handover_events') is not null and to_regclass('public.activity_eligibility') is not null"
    echo "--          and exists (select 1 from information_schema.columns where table_name='handover_events' and column_name='origin_room_id');"
    echo "-- (a current ProcessGPT database has them; this recreates their triggers and policies)"
    # the psql-only guard around the body (\gset / \if) is replaced by the check above
    perl -0pe 's/\A.*?\\if :lite_handover_ready\n\\else\n//s; s/\\endif\s*\z//s' "$here/compat/03_handover_events.sql"
  } > "$out/lite-prod-handover.sql"
fi
ls -l "$out"
