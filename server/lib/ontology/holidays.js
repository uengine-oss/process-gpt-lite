// the days off as a Set of 'YYYY-MM-DD' (Korea's calendar), with the company's own from PRO_HOLIDAYS
export function daysOff(extra = process.env.PRO_HOLIDAYS || '') {
  const set = new Set(Object.keys(KR))
  for (const s of String(extra).split(',').map((x) => x.trim()).filter(Boolean)) {
    if (/^-\d{4}-\d{2}-\d{2}$/.test(s)) set.delete(s.slice(1))
    else if (/^\d{4}-\d{2}-\d{2}$/.test(s)) set.add(s)
  }
  return set
}
